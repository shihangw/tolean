import { describe, expect, test } from 'vitest';

import { TranslateError, translateSource, translateWorkspace } from './translate.ts';

// These tests check that the package loads the WebAssembly translator and
// passes its options through. What the translator accepts and writes is
// checked on the corpus in tests/typescript and tests/go, against the same
// translator.
describe('translateSource', () => {
  test('translates a TypeScript file', async () => {
    const lean = await translateSource({
      fileName: 'input.ts',
      text: 'export function f(): boolean { return 0n - 1n < 0n; }',
      namespace: 'Test',
    });

    expect(lean).toContain('namespace Test');
    expect(lean).toContain('def f');
  });

  test('throws TranslateError with the file, line and reason', async () => {
    await expect(
      translateSource({
        fileName: 'input.ts',
        text: 'export function f(x: bigint): bigint { x = 1n; return x; }',
        namespace: 'Test',
      }),
    ).rejects.toThrow(TranslateError);
    await expect(
      translateSource({ fileName: 'input.ts', text: 'export function f(x: bigint): bigint { x = 1n; return x; }', namespace: 'Test' }),
    ).rejects.toThrow(/^input\.ts:1:40: only a local declared with let may be assigned/);
  });

  test('passes the target edition to the translator', async () => {
    const text = 'export function f(): bigint { return 1n; }';

    await expect(translateSource({ fileName: 'input.ts', text, namespace: 'Test', target: 'ES2019' })).rejects.toThrow(
      /does not have/,
    );
    const lean = await translateSource({ fileName: 'input.ts', text, namespace: 'Test', target: 'ES2022' });
    expect(lean).toMatch(/^-- Generated by tolean \d+\.\d+\.\d+ for ES2022 from input\.ts\./);
  });
});

describe('translateWorkspace', () => {
  test('translates each unit that tolean.json names, in any language', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{ "go": { "sources": ["calc/*.go"] } }' },
      { path: 'calc/calc.go', text: 'package calc\n\nfunc Double(x int64) int64 { return x + x }\n' },
    ]);

    expect(units).toHaveLength(1);
    expect(units[0]).toMatchObject({ kind: 'ok', output: 'calc/Calc.lean' });
  });

  test('throws TranslateError when tolean.json is missing', async () => {
    await expect(translateWorkspace([])).rejects.toThrow(TranslateError);
  });
});
