import { describe, expect, test } from 'vitest';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { TranslateError, translateSource, translateWorkspace } from './translate.ts';

// These tests check that the package runs the tolean binary and passes its
// options through. What the translator accepts and writes is checked on the
// corpus in tests/typescript and tests/go, with the same binary. Run them with
// TOLEAN_BINARY set, as CI does, until the platform packages exist.
describe('translateSource', () => {
  test.each(['../input.ts', 'src/../input.ts', '/tmp/input.ts', 'src/input.ts', 'input.ts'])(
    'preserves the supplied filename %s in output and diagnostics',
    async (fileName) => {
      const lean = await translateSource({
        fileName,
        text: 'export function f(): bigint { return 1n; }',
        namespace: 'Test',
      });
      expect(lean.split('\n')[0]).toContain(`from ${fileName}.`);
      expect(lean).toContain('namespace Test');
      expect(lean).toContain('def f');
      const invalid = translateSource({
        fileName,
        text: 'export function f(x: bigint): bigint { x = 1n; return x; }',
        namespace: 'Test',
      });
      await expect(invalid).rejects.toThrow(TranslateError);
      await expect(invalid).rejects.toThrow(
        `${fileName}:1:40: only a local declared with let may be assigned`,
      );
    },
  );

  test('translates a TypeScript file', async () => {
    const lean = await translateSource({
      fileName: 'input.ts',
      text: 'export function f(): boolean { return 0n - 1n < 0n; }',
      namespace: 'Test',
    });

    expect(lean).toContain('namespace Test');
    expect(lean).toContain('def f');
  });

  test('throws TranslateError with the file, line and reason', async () => {
    await expect(
      translateSource({
        fileName: 'input.ts',
        text: 'export function f(x: bigint): bigint { x = 1n; return x; }',
        namespace: 'Test',
      }),
    ).rejects.toThrow(TranslateError);
    await expect(
      translateSource({ fileName: 'input.ts', text: 'export function f(x: bigint): bigint { x = 1n; return x; }', namespace: 'Test' }),
    ).rejects.toThrow(/^input\.ts:1:40: only a local declared with let may be assigned/);
  });

  test('passes the target edition to the translator', async () => {
    const text = 'export function f(): bigint { return 1n; }';

    await expect(translateSource({ fileName: 'input.ts', text, namespace: 'Test', target: 'ES2019' })).rejects.toThrow(
      /does not have/,
    );
    const lean = await translateSource({ fileName: 'input.ts', text, namespace: 'Test', target: 'ES2022' });
    expect(lean).toMatch(/^-- Generated by tolean \d+\.\d+\.\d+ for ES2022 from input\.ts\./);
  });
});

describe('translateWorkspace', () => {
  const source = 'export function f(): bigint { return 1n; }';
  const user = (path: string) => `import { f } from "${path}"; export function g(): bigint { return f(); }`;

  test('excludes external source entries even when the config selects them', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts","../*.ts","src/../../*.ts"]}}' },
      { path: 'input.ts', text: source },
      { path: '../external.ts', text: source },
      { path: 'src/../../external.ts', text: source },
    ]);
    expect(units).toHaveLength(1);
    expect(units[0]).toMatchObject({ kind: 'ok', output: 'Input.lean' });
  });

  test.each([
    ['bundler', './lib'],
    ['bundler', './lib.js'],
    ['node16', './lib.js'],
    ['nodenext', './lib.js'],
  ])('resolves %s imports of %s', async (moduleResolution, path) => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: JSON.stringify({ typescript: { sources: ['*.ts'], moduleResolution } }) },
      { path: 'main.ts', text: user(path) },
      { path: 'lib.ts', text: source },
    ]);
    expect(units.every((u) => u.kind === 'ok')).toBe(true);
    expect(units.find((u) => u.kind === 'ok' && u.output === 'Main.lean')).toMatchObject({
      kind: 'ok', lean: expect.stringContaining('import Lib'),
    });
  });

  test('reads JSONC and gives tsconfig precedence over the project fallback', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"],"moduleResolution":"node16"}}' },
      { path: 'tsconfig.json', text: '{/* options */"compilerOptions":{"moduleResolution":"Bundler",},}' },
      { path: 'main.ts', text: user('./lib') },
      { path: 'lib.ts', text: source },
    ]);
    expect(units.every((u) => u.kind === 'ok')).toBe(true);
  });

  test('prefers index.ts as a file before any unsupported file target', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"],"moduleResolution":"bundler"}}' },
      { path: 'main.ts', text: user('./index') },
      { path: 'index.ts', text: source },
      { path: 'index.tsx', text: source },
    ]);
    expect(units.every((u) => u.kind === 'ok')).toBe(true);
  });

  const base = '{"compilerOptions":{"moduleResolution":"bundler","module":"esnext","strict":true,"noEmit":true}}';
  const inheritanceCases = [
    { name: 'issue 250', configs: { 'tsconfig.json': '{"extends":"./base.json","include":["src"]}', 'base.json': base }, mode: 'bundler', path: './lib' },
    { name: 'inherited bundler with .js', configs: { 'tsconfig.json': '{"extends":"./base.json"}', 'base.json': base }, mode: 'bundler', path: './lib.js' },
    { name: 'two bases in a chain', configs: { 'tsconfig.json': '{"extends":"./config/middle"}', 'config/middle.json': '{"extends":"../base.json"}', 'base.json': base }, mode: 'bundler', path: './lib' },
    { name: 'later array base wins', configs: { 'tsconfig.json': '{"extends":["./node.json","./base.json"]}', 'node.json': '{"compilerOptions":{"moduleResolution":"node16"}}', 'base.json': base }, mode: 'bundler', path: './lib' },
    { name: 'child overrides moduleResolution', configs: { 'tsconfig.json': '{"extends":"./base.json","compilerOptions":{"moduleResolution":"nodenext","module":"nodenext"}}', 'base.json': base }, mode: 'nodenext', path: './lib.js' },
    { name: 'shared ancestor is not a cycle', configs: { 'tsconfig.json': '{"extends":["./left.json","./right.json"]}', 'left.json': '{"extends":"./base.json","compilerOptions":{"moduleResolution":"node16"}}', 'right.json': '{"extends":"./base.json"}', 'base.json': base }, mode: 'bundler', path: './lib' },
  ];

  function showConfig(files: { path: string; text: string }[]) {
    const workspace = mkdtempSync(join(tmpdir(), 'tolean-extends-'));
    const dir = join(workspace, 'packages/geometry');
    try {
      for (const file of files) {
        const path = join(dir, file.path);
        mkdirSync(dirname(path), { recursive: true });
        writeFileSync(path, file.text);
      }
      return spawnSync(process.execPath, [createRequire(import.meta.url).resolve('typescript/bin/tsc'), '--showConfig', '-p', dir], { encoding: 'utf8' });
    } finally {
      rmSync(workspace, { recursive: true, force: true });
    }
  }

  test.each(inheritanceCases)('merges extends like tsc: $name', async ({ configs, mode, path }) => {
    const files = [
      { path: 'tolean.json', text: '{"typescript":{"sources":["src/*.ts"],"moduleResolution":"classic"}}' },
      ...Object.entries(configs).map(([path, text]) => ({ path, text })),
      { path: 'src/main.ts', text: `import { double } from "${path}"; export function quadruple(n: number): number { return double(double(n)); }` },
      { path: 'src/lib.ts', text: 'export function double(n: number): number { return n * 2; }' },
    ];
    const shown = showConfig(files);
    expect(shown.status, shown.stdout + shown.stderr).toBe(0);
    expect(JSON.parse(shown.stdout).compilerOptions.moduleResolution).toBe(mode);
    const units = await translateWorkspace(files);
    expect(units.every((u) => u.kind === 'ok')).toBe(true);
    expect(units.find((u) => u.kind === 'ok' && u.output === 'src/Main.lean')).toMatchObject({
      kind: 'ok', lean: expect.stringContaining('import src.Lib'),
    });
  });

  test.each(['moduleSuffixes', 'rootDirs'])('refuses inherited %s after merging', async (key) => {
    const files = [
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"]}}' },
      { path: 'tsconfig.json', text: '{"extends":"./base.json","compilerOptions":{"moduleResolution":"bundler"}}' },
      { path: 'base.json', text: JSON.stringify({ compilerOptions: { moduleResolution: 'bundler', [key]: ['.native', ''] } }) },
      { path: 'lib.ts', text: source },
    ];
    const shown = showConfig(files);
    expect(shown.status, shown.stdout + shown.stderr).toBe(0);
    expect(JSON.parse(shown.stdout).compilerOptions[key]).toHaveLength(2);
    await expect(translateWorkspace(files)).rejects.toThrow(`${key} is not supported`);
  });

  test('detects config cycles like tsc', async () => {
    const files = [
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"]}}' },
      { path: 'tsconfig.json', text: '{"extends":"./base.json"}' },
      { path: 'base.json', text: '{"extends":"./nested/../tsconfig.json"}' },
      { path: 'lib.ts', text: source },
    ];
    const shown = showConfig(files);
    expect(shown.status).not.toBe(0);
    expect(shown.stdout).toContain('Circularity');
    await expect(translateWorkspace(files)).rejects.toThrow(/extends cycle.*tsconfig.json.*base.json.*tsconfig.json/);
  });

  test.each([
    ['{"extends":"./missing.json"}', /has no config file/],
    ['{"extends":"@tsconfig/node22"}', /package or absolute extends/],
    ['{"extends":"../base.json"}', /extends '\.\.\/base.json' has no config file/],
    ['{"extends":["./base.json",42]}', /array of strings/],
  ])('refuses unsupported extends: %s', async (text, error) => {
    await expect(translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"]}}' },
      { path: 'tsconfig.json', text },
      { path: 'lib.ts', text: source },
    ])).rejects.toThrow(error);
  });

  test('reports invalid base JSON even when the child overrides its options', async () => {
    await expect(translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"]}}' },
      { path: 'tsconfig.json', text: '{"extends":"./base.json","compilerOptions":{"moduleResolution":"bundler"}}' },
      { path: 'base.json', text: '{"compilerOptions":42}' },
      { path: 'lib.ts', text: source },
    ])).rejects.toThrow(/base.json: compilerOptions must be an object/);
  });

  test('loads the shared monorepo base without imports like tsc', async () => {
    const files = [
      { path: 'tolean.json', text: '{"typescript":{"sources":["src/*.ts"]}}' },
      { path: 'tsconfig.json', text: '{"extends":"../../tsconfig.base.json","include":["src"]}' },
      { path: '../../tsconfig.base.json', text: base },
      { path: 'src/area.ts', text: 'export function area(w: number, h: number): number { return w * h; }' },
    ];
    const shown = showConfig(files);
    expect(shown.status, shown.stdout + shown.stderr).toBe(0);
    expect(JSON.parse(shown.stdout).compilerOptions.moduleResolution).toBe('bundler');
    const units = await translateWorkspace(files);
    expect(units).toHaveLength(1);
    expect(units[0]).toMatchObject({ kind: 'ok', output: 'src/Area.lean' });
  });

  test.each(['{} /*', '{"compilerOptions":{"moduleResolution":42}}', '[]', '{"compilerOptions":42}'])(
    'refuses an invalid tsconfig: %s', async (text) => {
      await expect(translateWorkspace([
        { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"]}}' },
        { path: 'tsconfig.json', text },
        { path: 'lib.ts', text: source },
      ])).rejects.toThrow(/tsconfig.json/);
    },
  );

  test.each(['bundler', 'node16', 'nodenext'])('keeps unsafe paths refused under %s', async (moduleResolution) => {
    for (const path of ['./lib.tsx', './lib.d.ts', './lib.d.js', './lib.json', 'lib', './lib%2Ets', './lib.ts?x', './lib.ts#x', './lib.ts/.', '../lib.js']) {
      const units = await translateWorkspace([
        { path: 'tolean.json', text: JSON.stringify({ typescript: { sources: ['main.ts'], moduleResolution } }) },
        { path: 'main.ts', text: user(path) },
        { path: 'lib.d.ts', text: source },
      ]);
      expect(units).toMatchObject([{ kind: 'error' }]);
    }
  });

  test('does not use the fallback when a tsconfig has no resolution setting', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{"typescript":{"sources":["*.ts"],"moduleResolution":"bundler"}}' },
      { path: 'tsconfig.json', text: '{}' },
      { path: 'main.ts', text: user('./lib') },
      { path: 'lib.ts', text: source },
    ]);
    expect(units.some((u) => u.kind === 'error')).toBe(true);
  });

  test('translates each unit that tolean.json names, in any language', async () => {
    const units = await translateWorkspace([
      { path: 'tolean.json', text: '{ "go": { "sources": ["calc/*.go"] } }' },
      { path: 'calc/calc.go', text: 'package calc\n\nfunc Double(x int64) int64 { return x + x }\n' },
    ]);

    expect(units).toHaveLength(1);
    expect(units[0]).toMatchObject({ kind: 'ok', output: 'calc/Calc.lean' });
  });

  test('throws TranslateError when tolean.json is missing', async () => {
    await expect(translateWorkspace([])).rejects.toThrow(TranslateError);
  });
});
