// The pages of the docs site. The Markdown files in the repository are the
// only source: `README.md` and every Markdown file under `docs/`. This module
// reads them, gives each one its URL, its category, its title, its first
// sentence and, for a plan or a decision, its status. It also writes the two
// files that VitePress reads but nobody commits: `overview.md`, a copy of the
// root README, and `index.md`, the front page.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const repoRoot = path.resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');
export const docsDir = path.join(repoRoot, 'docs');
export const githubRepo = 'https://github.com/shihangw/tolean';

// CI sets GITHUB_SHA. A local build uses the checked-out commit.
export const commit =
  process.env.GITHUB_SHA ??
  execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' }).trim();

export const githubUrl = (repoPath: string, kind: 'blob' | 'tree' = 'blob') =>
  `${githubRepo}/${kind}/${commit}/${repoPath}`;

// The categories in the order that the sidebar and the front page show them.
export const categories = ['Overview', 'Languages', 'Guides', 'Comparisons', 'Plans', 'Decisions'];

// The files that this module writes into `docs/`. Each starts with a marker,
// so that a build never overwrites a file that someone wrote by hand.
const generatedMarker = '<!-- Generated by docs/.vitepress/pages.ts. Do not edit. -->';
const overviewFile = 'overview.md';
const indexFile = 'index.md';

export interface Page {
  // The file's path from the repository root, such as `docs/go/README.md`.
  source: string;
  // The file that VitePress reads, from `docs/`, such as `go/README.md`.
  file: string;
  // The page that VitePress writes, from `docs/`, such as `go/index.md`.
  page: string;
  // The page's URL without the site's base, such as `/go/`.
  link: string;
  category: string;
  title: string;
  summary: string;
  status?: string;
}

function markdownFiles(dir: string): string[] {
  const files: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...markdownFiles(full));
    else if (entry.name.endsWith('.md')) files.push(full);
  }
  return files;
}

const isGenerated = (file: string) =>
  fs.existsSync(file) && fs.readFileSync(file, 'utf8').startsWith(generatedMarker);

function categoryOf(source: string, text: string): string {
  const comment = text.match(/^<!--\s*category:\s*(.+?)\s*-->/);
  if (comment) {
    if (!categories.includes(comment[1]))
      throw new Error(`${source}: unknown category "${comment[1]}". The categories are ${categories.join(', ')}.`);
    return comment[1];
  }
  if (source === 'README.md') return 'Overview';
  if (source.startsWith('docs/plans/')) return 'Plans';
  if (source.startsWith('docs/decisions/')) return 'Decisions';
  if (/^docs\/[^/]+\/README\.md$/.test(source)) return 'Languages';
  if (/^docs\/vs_[^/]+\.md$/.test(source)) return 'Comparisons';
  return 'Guides';
}

// Markdown inline syntax as plain text: a link becomes its text, an image
// disappears, and emphasis loses its markers. Code spans keep their backticks,
// because the front page renders the summary as Markdown.
const plainText = (s: string) =>
  s
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, '')
    .replace(/(\*\*|__)(.+?)\1/g, '$2')
    .replace(/\s+/g, ' ')
    .trim();

function describe(source: string, text: string) {
  const lines = text.split('\n');
  let title: string | undefined;
  let status: string | undefined;
  let summary: string | undefined;
  let fence = false;
  for (let i = 0; i < lines.length && summary === undefined; i++) {
    const line = lines[i];
    if (/^\s*(```|~~~)/.test(line)) fence = !fence;
    if (fence) continue;
    if (title === undefined) {
      const heading = line.match(/^# (.+)$/);
      if (heading) title = plainText(heading[1]);
      continue;
    }
    const statusLine = line.match(/^\*\*Status:\*\*\s*(.+?)\s*(·.*)?$/);
    if (statusLine) {
      status = statusLine[1];
      continue;
    }
    // The first paragraph of prose after the title. Headings, lists, tables,
    // images and HTML do not count.
    if (line.trim() === '' || /^\s*([#<!|>*-]|\d+\.)/.test(line)) continue;
    const paragraph: string[] = [];
    while (i < lines.length && lines[i].trim() !== '') paragraph.push(lines[i++]);
    const prose = plainText(paragraph.join(' '));
    summary = prose.match(/^.+?[.!?](?=\s|$)/)?.[0] ?? prose;
  }
  if (title === undefined) throw new Error(`${source}: the file has no top-level heading, so its page has no title.`);
  return { title, status, summary: summary ?? '' };
}

export function readPages(): Page[] {
  const sources = [
    'README.md',
    ...markdownFiles(docsDir)
      .filter((f) => !isGenerated(f))
      .map((f) => path.relative(repoRoot, f).split(path.sep).join('/')),
  ];
  const pages: Page[] = [];
  const byPage = new Map<string, string>([[indexFile, 'the front page']]);
  for (const source of sources) {
    const text = fs.readFileSync(path.join(repoRoot, source), 'utf8');
    const file = source === 'README.md' ? overviewFile : source.slice('docs/'.length);
    const page = file.replace(/(^|\/)README\.md$/, '$1index.md');
    const clash = byPage.get(page);
    if (clash) throw new Error(`${source} and ${clash} would both be the page ${page}.`);
    byPage.set(page, source);
    const link = '/' + page.replace(/(^|\/)index\.md$/, '$1').replace(/\.md$/, '');
    const category = categoryOf(source, text);
    const { title, status, summary } = describe(source, text);
    if (category === 'Plans' && status === undefined)
      throw new Error(`${source}: a plan needs a line "**Status:** …" under its title.`);
    pages.push({ source, file, page, link, category, title, summary, status });
  }
  return pages.sort(
    (a, b) => categories.indexOf(a.category) - categories.indexOf(b.category) || a.title.localeCompare(b.title),
  );
}

function frontPage(pages: Page[]): string {
  const out = [
    generatedMarker,
    '',
    '# Tolean docs',
    '',
    `Each page here is a Markdown file in the [Tolean repository](${githubRepo}).`,
    `This build is from commit [\`${commit.slice(0, 7)}\`](${githubRepo}/commit/${commit}).`,
  ];
  for (const category of categories) {
    const inCategory = pages.filter((p) => p.category === category);
    if (inCategory.length === 0) continue;
    out.push('', `## ${category}`, '');
    for (const p of inCategory) {
      const status = p.status ? ` *(${p.status})*` : '';
      out.push(`- [${p.title}](${p.link})${status}: ${p.summary}`);
    }
  }
  return out.join('\n') + '\n';
}

// Write `overview.md` and `index.md` into `docs/`, unless they are current.
export function writeGenerated(pages: Page[] = readPages()) {
  const write = (name: string, text: string) => {
    const file = path.join(docsDir, name);
    if (fs.existsSync(file) && !isGenerated(file))
      throw new Error(`docs/${name} is a page that the build generates, so the repository cannot have one.`);
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
  };
  write(overviewFile, generatedMarker + '\n' + fs.readFileSync(path.join(repoRoot, 'README.md'), 'utf8'));
  write(indexFile, frontPage(pages));
}
